import java.util.*;

public class Array {
    public static void main(String[] args) {
        Double abc[] = new Double[5];
        abc[0] = 38.9;
        abc[1] = 4.0; 
        abc[3] = 6.0;

        System.out.println("abc[0]: " + abc[0]);  
        System.out.println("abc[2]: " + abc[2]);  
    }
}
